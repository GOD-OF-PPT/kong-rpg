const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');

const assetMap = {
  mountain:     ['assets/art-v3/packed/mountain.webp',     'assets/art-v1/mountain-approach.png'],
  ferry:        ['assets/art-v3/packed/ferry.webp',        'assets/art-v1/lantern-ferry.png'],
  sanctuary:    ['assets/art-v3/packed/sanctuary.webp',    'assets/art-v1/ruined-sanctuary.png'],
  lotusRealm:   ['assets/art-v3/packed/lotusRealm.webp',   'assets/art-v3/black-lotus-realm.png'],
  titleBg:      ['assets/art-v3/packed/titleBg.webp',      'assets/art-v3/title-eclipse.png'],
  wukong:       ['assets/art-v3/packed/wukong.webp',       'assets/art-v1/wukong-atlas.png'],
  enemies:      ['assets/art-v3/packed/enemies.webp',      'assets/art-v1/enemy-atlas.png'],
  stone:        ['assets/art-v3/packed/stone.webp',        'assets/art-v1/stone-platform.png'],
  run:          ['assets/art-v3/packed/run.webp',          'assets/art-v2/wukong-run.png'],
  props:        ['assets/art-v3/packed/props.webp',        'assets/art-v2/journey-props.png'],
  relicIcons:   ['assets/art-v3/packed/relicIcons.png',    'assets/art-v3/relic-icons.png'],
  shrines:      ['assets/art-v3/packed/shrines.png',       'assets/art-v3/world-shrines.png'],
  eliteEnemies: ['assets/art-v3/packed/eliteEnemies.png',  'assets/art-v3/elite-enemies.png'],
  bossesV4:     ['assets/art-v3/packed/bossesV4.png',      'assets/art-v3/bosses-v4.png'],
  propsV4:      ['assets/art-v3/packed/propsV4.png',       'assets/art-v3/props-v4.png']
};

const manifest = { tool: 'built-in image_gen', runtime: 'embedded data URLs; no network or fetch', assets: {} };
const encoded = {};
for (const [key, candidates] of Object.entries(assetMap)) {
  const rel = candidates.find(c => fs.existsSync(path.join(root, c)));
  if (!rel) throw new Error('Missing asset for key: ' + key);
  const file = path.join(root, rel), data = fs.readFileSync(file);
  const mime = rel.endsWith('.webp') ? 'image/webp' : 'image/png';
  manifest.assets[key] = {
    file: rel,
    bytes: data.length,
    sha256: crypto.createHash('sha256').update(data).digest('hex')
  };
  encoded[key] = `data:${mime};base64,` + data.toString('base64');
}

const source = `/* Generated by tools/pack-art.cjs from workspace-owned ImageGen assets. */\n(function(K){const urls=${JSON.stringify(encoded)};K.ImageArt={images:{},errors:[],ready:null};K.ImageArt.ready=Promise.all(Object.entries(urls).map(([key,url])=>new Promise(resolve=>{const image=new Image();image.onload=()=>{K.ImageArt.images[key]=image;resolve();};image.onerror=()=>{K.ImageArt.errors.push(key);resolve();};image.src=url;})));})(globalThis.Kong ||= {});\n`;
fs.writeFileSync(path.join(root, 'src/generated-art.js'), source);
fs.writeFileSync(path.join(root, 'assets/art-v2/manifest.json'), JSON.stringify(manifest, null, 2));
console.log('Embedded', Object.keys(encoded).length, 'ImageGen assets;', Buffer.byteLength(source), 'bytes');
